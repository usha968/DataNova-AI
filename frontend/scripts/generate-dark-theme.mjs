// Generates src/theme-dark.css from src/index.css + src/App.css.
// Every declaration that sets a color gets a twin scoped under html[data-theme="dark"] with the color
// remapped by role (surface / border / text). All twins gain the same specificity, so the light
// cascade order is preserved. Re-run with `npm run theme:dark` after editing the light styles.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const src = join(dirname(fileURLToPath(import.meta.url)), '..', 'src')
const SCOPE = 'html[data-theme="dark"]'
const COLOR_PROPS = /^(color|background|background-color|background-image|border|border-(top|right|bottom|left)|border(-(top|right|bottom|left))?-color|outline|outline-color|box-shadow|fill|stroke|caret-color|text-decoration-color|accent-color)$/

function hexToRgba(hex) {
  let h = hex.slice(1)
  if (h.length <= 4) h = [...h].map((c) => c + c).join('')
  const n = (i) => parseInt(h.slice(i, i + 2), 16)
  return [n(0), n(2), n(4), h.length === 8 ? n(6) / 255 : 1]
}
function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2
  if (max === min) return [0, 0, l * 100]
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4
  return [h * 60, s * 100, l * 100]
}
const hsla = (h, s, l, a) => a < 1 ? `hsla(${h.toFixed(0)},${s.toFixed(0)}%,${l.toFixed(1)}%,${a.toFixed(2)})` : `hsl(${h.toFixed(0)},${s.toFixed(0)}%,${l.toFixed(1)}%)`

const mappers = {
  // Page, card, badge and hover fills: near-whites become dark greys (keeping their elevation order),
  // pastel tints become muted dark tints, strong fills (buttons, dots) stay vivid.
  surface(h, s, l) {
    // Warm/cool off-whites all become one cool neutral so panels match the page background.
    if (l >= 94) return [215, 14, 7 + (l - 94) * 1.25]
    if (l >= 55) return [h, Math.min(s, 32), 14 + (94 - l) * 0.3]
    return [h, s, l < 30 ? l + 14 : l]
  },
  border(h, s, l) { return l >= 55 ? [h, Math.min(s, 14), 20 + (100 - l) * 0.3] : [h, s, l < 30 ? l + 14 : l] },
  // Text: dark ink becomes light, muted greys stay muted, white text on coloured buttons stays white.
  text(h, s, l) { return l >= 88 ? [h, s, l] : [h, s * 0.9, 92 - l * 0.5] },
}
function mapColor(hex, role) {
  const [r, g, b, a] = hexToRgba(hex)
  const [h, s, l] = rgbToHsl(r, g, b)
  if (role === 'shadow') return `rgba(0,0,0,${Math.min(0.6, a * 2.2).toFixed(2)})`
  return hsla(...mappers[role](h, s, l), a)
}
function roleFor(prop) {
  if (prop === 'box-shadow') return 'shadow'
  if (prop.startsWith('border') || prop.startsWith('outline')) return 'border'
  if (prop.startsWith('background')) return 'surface'
  return 'text'
}
const transformValue = (prop, value) => value.replace(/#[0-9a-fA-F]{3,8}\b/g, (hex) => mapColor(hex, roleFor(prop)))

function darkDecls(body) {
  return body.split(';').map((d) => d.trim()).filter(Boolean).flatMap((decl) => {
    const i = decl.indexOf(':')
    const prop = decl.slice(0, i).trim().toLowerCase(), value = decl.slice(i + 1).trim()
    if (prop.startsWith('--') || !COLOR_PROPS.test(prop)) return []
    // Non-hex values (inherit, var(), transparent) are copied too so relative specificity stays intact.
    return [`${prop}:${transformValue(prop, value)}`]
  })
}
const scopeSelector = (selectors) => selectors.split(',').map((sel) => {
  sel = sel.trim()
  if (sel === ':root' || sel === 'html') return SCOPE
  return `${SCOPE} ${sel}`
}).join(',')

function convert(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '')
  let out = '', i = 0
  while (i < css.length) {
    const open = css.indexOf('{', i)
    if (open === -1) break
    const head = css.slice(i, open).trim()
    let depth = 1, j = open + 1
    while (depth && j < css.length) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++ }
    const body = css.slice(open + 1, j - 1)
    const prelude = head.replace(/^[^{}]*;/, '').trim() // drop @import ...; statements before the rule
    if (prelude.startsWith('@media')) { const inner = convert(body); if (inner) out += `${prelude}{${inner}}\n` }
    else if (!prelude.startsWith('@')) { const decls = darkDecls(body); if (decls.length) out += `${scopeSelector(prelude)}{${decls.join(';')}}\n` }
    i = j
  }
  return out
}

const vars = {
  '--ink': '#e4e9f0', '--muted': '#97a3b4', '--line': '#2b3340', '--paper': '#171b21', '--cream': '#0f1216', '--navy': '#3d5f8c',
  '--mint': '#1d3a31', '--peach': '#43302a', '--lavender': '#2f2a45', '--blue': '#1f3540', '--yellow': '#3d3726', '--pink': '#402a33',
}
const header = `/* GENERATED by scripts/generate-dark-theme.mjs from index.css + App.css. Do not edit by hand; run \`npm run theme:dark\`. */\n`
const root = `${SCOPE}{color-scheme:dark;${Object.entries(vars).map(([k, v]) => `${k}:${v}`).join(';')}}\n${SCOPE} body{background:var(--cream);color:var(--ink)}\n`
const body = convert(readFileSync(join(src, 'index.css'), 'utf8')) + convert(readFileSync(join(src, 'App.css'), 'utf8'))
writeFileSync(join(src, 'theme-dark.css'), header + root + body)
console.log(`theme-dark.css: ${body.split('\n').length - 1} rules`)
